import assert from 'node:assert/strict';
import {mkdtemp} from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import * as ops from './daily-operations.mjs';
import {preflightChannel} from './daily-preflight.mjs';
import {makeReadyFixture} from './state-evidence-fixtures.mjs';

const base=await mkdtemp(path.join(os.tmpdir(),'springhues-original-source-'));
const f=await makeReadyFixture(base,'minsheng');
assert.equal((await preflightChannel(f.root,f)).ok,true);
const ledger=await ops.readResearchLedger(f.root,f.date);
const source=ledger.find(row=>row.section==='tech'&&row.candidateIds.length);
const original=source.candidateEvidence[0];
const pending={...original,facts:{...original.facts,originalVerificationPending:true}};
const record=async(e,eventId)=>ops.appendResearchLedger(f.root,{date:f.date,runId:f.runId,channel:'minsheng',section:'tech',sourceId:source.sourceId,status:'accepted',candidateIds:[e.id],candidateEvidence:[e],eventId,now:f.now});
await record(pending,'source-still-pending');
const incomplete=await ops.researchCompleteness(f.root,f.date,'minsheng');
assert.equal(incomplete.complete,false);
assert.deepEqual(incomplete.sections.tech.originalVerificationPendingIds,[original.id]);
assert(incomplete.sections.tech.evidenceMissingIds.includes(original.id));
const blocked=await preflightChannel(f.root,f);
assert.equal(blocked.gates.research.ok,false);
await assert.rejects(ops.createReadyProof(f.root,f),{code:'PRECHECK_FAILED'});
await record({...original,facts:{...original.facts,originalVerificationPending:false,primarySourceUrl:original.url}},'source-verified');
assert.equal((await ops.researchCompleteness(f.root,f.date,'minsheng')).complete,true);
assert.deepEqual((await ops.researchCompleteness(f.root,f.date,'minsheng')).sections.tech.originalVerificationPendingIds,[]);
assert.equal((await preflightChannel(f.root,f)).ok,true);
console.log('原始材料待核验会阻断研究、就绪及发布；最新有效核验记录可恢复门禁。保留夹具：'+base);
